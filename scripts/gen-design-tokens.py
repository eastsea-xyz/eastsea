def outputs(root, t, components):
    generated = css(t)
    files = {root / "apps/wallet/Sources/DesignTokens.swift": swift(t)}
    for folder, name in (("site", "tokens.css"), ("apps/extension/ui", "design-tokens.css"), ("apps/explorer", "design-tokens.css"), ("design/generated/toolbox", "design-tokens.css")):
        files[root / folder / name] = generated
        files[root / folder / "design-components.css"] = "/* GENERATED copy of design/brand/components.css. Do not edit. */\n" + components
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any packaged token or component file is stale")
    args = parser.parse_args(argv)
    try:
        tokens = validate(json.loads((ROOT / "design/brand/tokens.json").read_text()))
        files = outputs(ROOT, tokens, (ROOT / "design/brand/components.css").read_text())
    except (ValueError, KeyError, OSError, TypeError) as error:
        print(f"design tokens: {error}", file=sys.stderr)
        return 2
    stale = [path for path, content in files.items() if not path.exists() or path.read_text() != content]
    if args.check:
        if stale:
            for path in stale:
                print(f"DRIFT {path.relative_to(ROOT)}", file=sys.stderr)
            print("Run python3 scripts/gen-design-tokens.py", file=sys.stderr)
            return 1
        print(f"design tokens: {len(files)} generated files match v{tokens['version']}")
        return 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path])
        print(f"generated {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
